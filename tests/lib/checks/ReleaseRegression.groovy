/**
 * Compares the output tree of the current RustQC with that of the last released RustQC,
 * both run on the same dataset with the same arguments (tests/rna/regression/release.nf.test).
 *
 * Every file under `rustqc/` is compared exactly (as lines), except:
 *
 *   EXCLUDED_FILES   never compared: plots (PNG/SVG/PDF; rendering changes without the data
 *                    changing, and their data is in the .txt/.r/.xls files next to them) and
 *                    CITATIONS.md (lists the RustQC version)
 *   VOLATILE_LINES   lines dropped before comparing: version and command-line headers
 *   MOTIF_ROWS       Qualimap junction-motif rows, compared per group of tied
 *                    percentages (RustQC lists tied motifs in a random order)
 *
 * Measured on hs_chr6_pe_rev, v0.2.1 vs main (6b66655): only CITATIONS.md and the dupRadar
 * density plot differ in bytes; every other file is identical.
 *
 * A file present in the baseline but missing from the current run fails the check. A file
 * only the current run writes (a new output) is reported but does not fail.
 *
 * Intentional output changes since the baseline release are listed in tests/datasets.yml
 * under release_regression.accepted_differences ({path: glob, reason: why}); they are
 * reported, not failed. Clear that list whenever baseline_image is bumped.
 *
 * Environment:
 *   RUSTQC_BASELINE_BIN / RUSTQC_CURRENT_BIN   run two local binaries instead of two images
 */
package checks

import java.nio.file.FileSystems
import java.nio.file.Path
import java.nio.file.PathMatcher

class ReleaseRegression {

    /** Globs (relative to rustqc/) of files that are never compared. */
    static final List<String> EXCLUDED_FILES = [
        'CITATIONS.md',
        '**.png',
        '**.svg',
        '**.pdf',
    ].asImmutable()

    /** Lines that legitimately differ between versions (version / command-line headers). */
    static final List<Map> VOLATILE_LINES = [
        // featureCounts tables: "# Program:featureCounts v2.0.6, generated by RustQC v0.2.1; Command:..."
        [glob: 'featurecounts/**', regex: ~/^# Program:.*/],
        // samtools stats header ("# This file was produced by samtools stats and RustQC",
        // "# The command line was: ..."): constant today, but meant to carry version/command
        [glob: 'samtools/*.stats', regex: ~/^# (This file was produced by|The command line was:).*/],
        // Qualimap HTML report: "Analysis date" and the footer carry the run's wall-clock time
        [glob: 'qualimap/qualimapReport.html', regex: ~/.*\d{4}\/\d{2}\/\d{2} \d{2}:\d{2}:\d{2}.*/],
    ].asImmutable()

    /**
     * KNOWN ISSUE (RustQC): the Qualimap junction-motif list ("ACCT : 10.89%", in
     * rnaseq_qc_results.txt and as table rows in qualimapReport.html) is non-deterministic.
     * RustQC counts motifs in a std HashMap, whose iteration order is random per process, and
     * then stable-sorts them by frequency only (src/rna/qualimap/output.rs and report.rs), so
     * motifs with equal percentages come out in a different order on every run. Seen on
     * sc_pe_rev, sc_se_rev, hs_chr22_pe_fwd and hs_ribo_chr19_22_se_fwd.
     *
     * normaliseMotifs() compares each group of tied rows as a set (names sorted within the
     * group; percentages and group order still compared). The list stops at the top 11, so when
     * it is full the last tied group may be cut at a random member: its names are masked.
     * Remove this once a RustQC release with the tie-breaking fix is both the baseline and :dev.
     */
    static final Map<String, java.util.regex.Pattern> MOTIF_ROWS = [
        'qualimap/rnaseq_qc_results.txt': ~/^(\s+)([ACGTN]{4})( : )([\d.]+)(%)$/,
        'qualimap/qualimapReport.html'  : ~/^(<td class="column1">)([ACGTN]{4})(<\/td><td class="column2">)([\d.]+)(%<\/td>)$/,
    ].asImmutable()

    /** Qualimap lists at most this many junction motifs. */
    static final int MOTIF_LIMIT = 11

    // ── Test entry points ─────────────────────────────────────────────

    /** Label of the baseline for test names: the image tag, or "local baseline binary". */
    static String baselineLabel() {
        if (binDir('RUSTQC_BASELINE_BIN')) return 'local baseline binary'
        return datasets.Datasets.baselineImage().tokenize('/').last()
    }

    /**
     * Directory to put first on PATH for one of the two runs, from an environment variable
     * naming either a `rustqc` binary or a directory holding one. null when unset.
     */
    static String binDir(String envVar) {
        def value = System.getenv(envVar)
        if (!value) return null
        def f = new File(value).absoluteFile
        if (f.isFile()) {
            assert f.name == 'rustqc' : "${envVar}=${value}: the binary must be called `rustqc` (the module runs `rustqc rna`)"
            f = f.parentFile
        }
        assert new File(f, 'rustqc').canExecute() : "${envVar}=${value}: no executable `rustqc` there"
        return f.path
    }

    /**
     * Guard against a comparison that cannot fail:
     *  - the two runs must not be the same binary. RustQC prints its build in the log banner,
     *    "RustQC v0.2.1 (c868466, built 2026-04-09T12:09:17Z)"; identical banners mean both
     *    runs used one binary (e.g. a profile without containers and no RUSTQC_*_BIN set).
     *    The short `rustqc -V` in versions.yml is not enough: main keeps the release version
     *    number until the next release.
     *  - with images, the baseline must report the version of its image tag.
     * Arguments are the versions.yml paths of the two tasks; the banner is read from the
     * .command.log next to them.
     */
    static void assertBaselineVersion(def baselineVersionsYml, def currentVersionsYml) {
        String base = build(baselineVersionsYml)
        String cur  = build(currentVersionsYml)
        println "release regression: baseline ${base}, current ${cur}"
        assert base != cur : \
            "The baseline and current runs used the same RustQC binary (${base}), so the " +
            "comparison would be trivially exact. Use a profile with a container engine, or set " +
            "RUSTQC_BASELINE_BIN and RUSTQC_CURRENT_BIN to two different binaries (see tests/DATASETS.md)."
        if (binDir('RUSTQC_BASELINE_BIN')) return
        def tag = datasets.Datasets.baselineImage().tokenize(':').last()
        def m = tag =~ /^v?(\d+\.\d+\.\d+)/
        assert m.find() : "Cannot read a version from the baseline image tag '${tag}'"
        def expected = m.group(1)
        assert base.contains("v${expected} ") || base.contains("rustqc ${expected}") : \
            "The baseline run reports ${base}, not ${expected} from ${datasets.Datasets.baselineImage()}."
    }

    /** The RustQC build banner from a task's .command.log, or the versions.yml version. */
    private static String build(def versionsYml) {
        def yml = new File(versionsYml.toString())
        def log = new File(yml.parentFile, '.command.log')
        if (log.isFile()) {
            def m = log.text =~ /RustQC v\S+ \([0-9a-f]+, built [^)]+\)/
            if (m.find()) return m.group(0)
        }
        return "rustqc ${rustqcVersion(yml)}"
    }

    /** Compare the two `rustqc/` output trees of one dataset. Fails listing every difference. */
    static void compare(def ds, def currentDir, def baselineDir) {
        File current  = new File(currentDir.toString())
        File baseline = new File(baselineDir.toString())
        Map<String, String> accepted = acceptedDifferences(ds)

        def curFiles  = relativeFiles(current)
        def baseFiles = relativeFiles(baseline)

        List<String> failures = []
        List<String> notes = []

        (baseFiles - curFiles).sort().each { rel ->
            if (isExcluded(rel)) return
            def reason = acceptedReason(rel, accepted)
            if (reason) notes << "removed (accepted: ${reason}): ${rel}"
            else failures << "missing in current: ${rel}"
        }
        (curFiles - baseFiles).sort().each { rel ->
            if (!isExcluded(rel)) notes << "new in current: ${rel}"
        }
        (curFiles.intersect(baseFiles)).sort().each { rel ->
            if (isExcluded(rel)) return
            def diff = diffLines(rel, new File(current, rel), new File(baseline, rel))
            if (diff == null) return
            def reason = acceptedReason(rel, accepted)
            if (reason) notes << "differs (accepted: ${reason}): ${rel}"
            else failures << "differs: ${rel}\n${diff}"
        }

        int compared = curFiles.intersect(baseFiles).count { !isExcluded(it) } as int
        println "release regression [${ds.id}]: ${compared} files compared, " +
            "${failures.size()} unexpected difference(s)" +
            (notes ? "\n  " + notes.join('\n  ') : '')

        assert !failures : \
            "RustQC output on '${ds.id}' differs from the baseline release " +
            "(${failures.size()} file(s)). If the change is intentional, list the file under " +
            "release_regression.accepted_differences in tests/datasets.yml.\n\n" +
            failures.join('\n\n')
    }

    // ── Helpers ───────────────────────────────────────────────────────

    /** Files under `root`, as '/'-separated paths relative to it. */
    static Set<String> relativeFiles(File root) {
        assert root.isDirectory() : "Not a directory: ${root}"
        Set<String> out = [] as Set
        root.eachFileRecurse(groovy.io.FileType.FILES) { File f ->
            out << root.toPath().relativize(f.toPath()).toString().replace(File.separator, '/')
        }
        return out
    }

    static boolean isExcluded(String rel) {
        return EXCLUDED_FILES.any { glob(it).matches(Path.of(rel)) }
    }

    /**
     * null when the two files are equal after dropping VOLATILE_LINES, else a short report
     * of the first differing lines.
     */
    static String diffLines(String rel, File cur, File base, int maxShown = 10) {
        if (cur.bytes == base.bytes) return null
        def dropped = VOLATILE_LINES.findAll { glob(it.glob as String).matches(Path.of(rel)) }*.regex
        def keep = { List<String> lines ->
            normaliseMotifs(rel, lines.findAll { line -> !dropped.any { line ==~ it } })
        }
        List<String> a = keep(cur.readLines())
        List<String> b = keep(base.readLines())
        if (a == b) return null
        List<String> shown = []
        int n = Math.max(a.size(), b.size())
        for (int i = 0; i < n && shown.size() < maxShown; i++) {
            def x = i < a.size() ? a[i] : '<none>'
            def y = i < b.size() ? b[i] : '<none>'
            if (x != y) shown << "    line ${i + 1}:\n      current:  ${x}\n      baseline: ${y}"
        }
        def header = a.size() == b.size() ? '' : "    line count: current ${a.size()}, baseline ${b.size()}\n"
        return header + shown.join('\n')
    }

    /**
     * The junction-motif rows of a Qualimap output with each run of equal percentages sorted by
     * motif name, and the names of the last run masked when the list is full (see MOTIF_ROWS).
     * Other files and lines are returned unchanged.
     */
    static List<String> normaliseMotifs(String rel, List<String> lines) {
        java.util.regex.Pattern pattern = MOTIF_ROWS[rel]
        if (pattern == null) return lines
        List<String> out = new ArrayList<String>(lines)
        List<Integer> rows = []
        List<java.util.regex.Matcher> found = []
        for (int i = 0; i < lines.size(); i++) {
            def m = pattern.matcher(lines[i])
            if (m.matches()) {
                rows << i
                found << m
            }
        }
        int start = 0
        while (start < rows.size()) {
            int end = start
            while (end + 1 < rows.size() && found[end + 1].group(4) == found[start].group(4)) end++
            boolean cutOff = rows.size() == MOTIF_LIMIT && end == rows.size() - 1
            List<String> names = (start..end).collect { found[it].group(2) }.sort()
            for (int k = start; k <= end; k++) {
                def m = found[k]
                String name = cutOff ? '<tied motif>' : names[k - start]
                out[rows[k]] = m.group(1) + name + m.group(3) + m.group(4) + m.group(5)
            }
            start = end + 1
        }
        return out
    }

    /** release_regression.accepted_differences from tests/datasets.yml: glob -> reason. */
    static Map<String, String> acceptedDifferences(def ds) {
        def list = datasets.Datasets.manifest().release_regression?.accepted_differences ?: []
        return list.findAll { entry ->
            // An entry may be limited to some datasets with `datasets: [id, ...]`.
            !entry.datasets || ds.id in entry.datasets
        }.collectEntries { entry ->
            assert entry.path && entry.reason : \
                "release_regression.accepted_differences entries need `path` and `reason`: ${entry}"
            [((entry.path as String).replace('{sample}', ds.sample as String)): entry.reason as String]
        }
    }

    static String acceptedReason(String rel, Map<String, String> accepted) {
        def hit = accepted.find { glob(it.key).matches(Path.of(rel)) }
        return hit?.value
    }

    private static PathMatcher glob(String pattern) {
        return FileSystems.default.getPathMatcher("glob:${pattern}")
    }

    private static String rustqcVersion(def versionsYml) {
        def text = new File(versionsYml.toString()).text
        def m = text =~ /(?m)^\s*rustqc:\s*(.+)$/
        assert m.find() : "No rustqc version in ${versionsYml}:\n${text}"
        return m.group(1).trim()
    }
}
